import { ROUTE_POLICY, SPECIAL_ROUTE_FILES, type RoutePolicy } from "../lib/api/route-policy";

const CATEGORY_MEANING: Record<string, string> = {
  public: "Public: no private tenant data, no financial action.",

  "signed-principal": "The caller signs with an Ed25519 principal whose chain is verified. No session.",
  "signed-agent": "An agent's signed request is the authority. Agents never hold a human session.",
  "signed-owner": "Signed by the account owner. Requires a session in the same organization from the next phase.",
  session: "Requires a validated server-side session, and enforces the permission named, for one organization.",
  webhook: "Provider-authenticated ingress. The event is a hint, never a tenant identity.",
  simulation: "Simulator only. Refused in production.",
  demo: "Demo only. Refused in production.",
  scheduler: "Internal scheduler, bearer secret. Refused in production when unconfigured.",
  "operator-key": "Operator tool behind a bearer secret.",
};

const row = (k: string, p: RoutePolicy) => `| \`${k}\` | ${p.category} | ${p.permission ? `\`${p.permission}\`` : "—"} | ${p.enforcement} | ${p.note} |`;

const banner = `<!-- Generated by scripts/route-matrix.ts from lib/api/route-policy.ts. Do not edit by hand. -->

# Milestone 4.1 — route authorization matrix

Every registered handler and every route file, classified. \`tests/route-authorization.test.ts\` fails if a route is
missing here, if an entry is stale, or if a handler is not mounted by a route file.

**Read the \`enforcement\` column as the truth.** Every row is \`enforced\`: there is no classified route whose
check is still to come.

Since Milestone 4.4 every route that reads one organization's records is classified \`session\`, and
\`lib/api/next.ts\` enforces it: no valid session is a 401, the permission in this table is checked against the
caller's membership role, and the read runs inside a transaction that carries the caller's organization, so
another organization's id (or an unattributed row) is a 404. Row level security (migration 0016) narrows the same
reads again inside the database.

The public surface is the **signed-only proof graph** (\`/api/proof/…\`): signed records anyone may re-verify in
their own browser, with nothing private added. A receipt with live provider checks, an envelope's tree, an
organization's books and its provider statement are not public.

## Categories
`;

const out: string[] = [banner];
for (const [cat, meaning] of Object.entries(CATEGORY_MEANING)) out.push(`* **${cat}** — ${meaning}`);
out.push("");
out.push("## Registered handlers");
out.push("");
out.push("| Route | Category | Permission | Enforcement | Note |");
out.push("| --- | --- | --- | --- | --- |");
